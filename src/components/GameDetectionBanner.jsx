import React, { useState, useEffect, useMemo } from 'react';
import { useGameDetection } from '../hooks/useGameDetection';
import { useAutoSync } from '../hooks/useAutoSync';
import useStore from '../store/useStore';
import SteamConfigDialog from './SteamConfigDialog';
import TemplateBrowser from './TemplateBrowser';

// One line of the Steam scan result: click to reveal the localized description
function AchievementLine({ achievement }) {
  const [open, setOpen] = useState(false);
  const label = (achievement.display || achievement.key || '').toString();
  const hasDescription = Boolean(achievement.description);
  return (
    <div>
      <button
        type="button"
        onClick={() => hasDescription && setOpen((v) => !v)}
        title={hasDescription ? 'Cliquer pour voir le descriptif' : label}
        className={`w-full text-left truncate ${
          achievement.unlocked ? 'text-emerald-400' : 'text-white/40'
        } ${hasDescription ? 'hover:underline cursor-pointer' : 'cursor-default'}`}
      >
        {achievement.unlocked ? '\u2713' : '\u25CB'} {label}
        {hasDescription && <span className="text-white/25"> {open ? '\u25BC' : '\u25B6'}</span>}
      </button>
      {open && hasDescription && (
        <div className="ml-3 mb-1 pl-2 border-l border-white/15 text-white/50 whitespace-pre-wrap">
          {achievement.description}
        </div>
      )}
    </div>
  );
}

export default function GameDetectionBanner() {
  const { detectedGame, scanning, scanResult, scan, isElectron, refresh } = useGameDetection();
  const [open, setOpen] = useState(false);
  const {
    addGame, addZone, addItem, syncItemsFromSteam,
    gamesById, gameIds, currentGameId,
  } = useStore();

  // Find game by detected name to pass its id to useAutoSync
  const matchedGameId = useMemo(() => {
    if (!detectedGame) return null;
    const found = gameIds
      .map((id) => gamesById[id])
      .find((g) => g?.name === detectedGame.name);
    return found?.id || currentGameId || null;
  }, [detectedGame, gameIds, gamesById, currentGameId]);

  const { enabled: autoSyncEnabled, toggle: toggleAutoSync, autoChecked, lastEvent, scanSteamNow } = useAutoSync(
    matchedGameId,
    detectedGame?.id
  );

  const [steamConfigOpen, setSteamConfigOpen] = useState(false);
  const [browserOpen, setBrowserOpen] = useState(false);
  const [steamScanning, setSteamScanning] = useState(false);
  const [steamResult, setSteamResult] = useState(null);
  const [savePulse, setSavePulse] = useState(false);
  const [autoGenerating, setAutoGenerating] = useState(false);
  const [autoGenError, setAutoGenError] = useState(null);

  // Auto-generate a template for a Steam-detected unknown game
  const handleAutoGenerate = async () => {
    if (!detectedGame?.steamAppId) return;
    setAutoGenError(null);
    setAutoGenerating(true);
    try {
      const gen = await window.electronAPI.generateTemplate(detectedGame.steamAppId, {});
      if (!gen?.ok) throw new Error(gen?.error || 'G\u00e9n\u00e9ration impossible');
      const entry = {
        ...gen.entry,
        id: `steam-${detectedGame.steamAppId}`,
        name: detectedGame.name,
        steamAppId: detectedGame.steamAppId,
        processNames: detectedGame.processNames || [],
      };
      const saved = await window.electronAPI.saveTemplate(entry);
      if (!saved?.ok) throw new Error(saved?.error || 'Sauvegarde impossible');
      importRegistryGame(saved.entry || entry);
      // Trigger re-detect so the banner stops marking as autoGenerated
      await refresh();
    } catch (e) {
      setAutoGenError(e.message);
    } finally {
      setAutoGenerating(false);
    }
  };

  // Import a registry game (with template) into the local store
  const importRegistryGame = (regGame) => {
    if (!regGame) return;
    const existing = gameIds.map((id) => gamesById[id]).find((g) => g?.name === regGame.name);
    const tmpl = regGame.checklistTemplate;
    const descMap = regGame.steamAchievementDescriptions || {};

    const readItem = (it) => {
      const name = typeof it === 'string' ? it : it?.name;
      if (!name) return null;
      const steamKey = typeof it === 'string' ? null : it?.steamKey || null;
      return {
        name,
        steamKey,
        description:
          (typeof it === 'string' ? null : it?.description) || descMap[steamKey] || null,
        hidden: typeof it === 'string' ? false : !!it?.hidden,
      };
    };

    // Already imported: don't duplicate the zones, just re-align the labels.
    if (existing) {
      const entries = (tmpl?.zones || []).flatMap((z) =>
        (z.items || [])
          .map(readItem)
          .filter(Boolean)
          .map((it) => ({ ...it, aliases: [(regGame.steamAchievementMap || {})[it.steamKey]] }))
      );
      syncItemsFromSteam(existing.id, entries);
      return;
    }

    const gameId = addGame(regGame.name);
    (tmpl?.zones || []).forEach((z) => {
      const zoneId = addZone(gameId, z.name);
      (z.items || []).forEach((raw) => {
        const it = readItem(raw);
        if (!it) return;
        addItem(gameId, zoneId, it.name, 1, {
          description: it.description,
          steamKey: it.steamKey,
          hidden: it.hidden,
        });
      });
    });
  };

  useEffect(() => {
    if (!lastEvent) return;
    setSavePulse(true);
    const t = setTimeout(() => setSavePulse(false), 2000);
    return () => clearTimeout(t);
  }, [lastEvent]);

  if (!isElectron) return null;

  // No game detected: show a small placeholder with a debug button
  if (!detectedGame) {
    return (
      <>
        <div className="bg-white/5 border border-white/10 rounded-lg px-3 py-2 flex items-center gap-2 text-xs">
          <div className="w-2 h-2 rounded-full bg-white/30" />
          <span className="text-white/40 flex-1 truncate">Aucun jeu d&eacute;tect&eacute;</span>
          <button
            onClick={() => setBrowserOpen(true)}
            className="px-2 py-0.5 bg-blue-500/20 hover:bg-blue-500/30 text-blue-200 rounded"
          >
            Templates
          </button>
          <button
            onClick={refresh}
            className="px-2 py-0.5 bg-white/10 hover:bg-white/20 text-white/60 rounded"
          >
            Scan
          </button>
          <button
            onClick={() => setSteamConfigOpen(true)}
            title="Configurer Steam"
            className="px-1.5 py-0.5 bg-white/10 hover:bg-white/20 text-white/60 rounded"
          >
            ⚙
          </button>
        </div>
        <SteamConfigDialog open={steamConfigOpen} onClose={() => setSteamConfigOpen(false)} />
        <TemplateBrowser
          open={browserOpen}
          onClose={() => setBrowserOpen(false)}
          onImport={importRegistryGame}
        />
      </>
    );
  }

  const handleScan = async () => {
    await scan(detectedGame.id);
    setOpen(true);
  };

  const handleImport = () => {
    if (!scanResult) return;

    // Check if game already exists by name
    const existingGame = gameIds
      .map((id) => gamesById[id])
      .find((g) => g?.name === detectedGame.name);

    let gameId;
    if (existingGame) {
      gameId = existingGame.id;
    } else {
      // Create from template if available
      const tmpl = detectedGame.checklistTemplate;
      const descMap = detectedGame.steamAchievementDescriptions || {};
      gameId = addGame(detectedGame.name);
      if (tmpl?.zones) {
        tmpl.zones.forEach((z) => {
          const zoneId = addZone(gameId, z.name);
          (z.items || []).forEach((it) => {
            const name = typeof it === 'string' ? it : it?.name;
            if (!name) return;
            const steamKey = typeof it === 'string' ? null : it?.steamKey || null;
            addItem(gameId, zoneId, name, 1, {
              description:
                (typeof it === 'string' ? null : it?.description) || descMap[steamKey] || null,
              steamKey,
              hidden: typeof it === 'string' ? false : !!it?.hidden,
            });
          });
        });
      }
    }

    // Add scanned items into a dedicated auto-detected zone
    if (scanResult.aggregated?.items?.length) {
      const zoneId = addZone(gameId, 'Détecté automatiquement');
      const seen = new Set();
      scanResult.aggregated.items.forEach((it) => {
        const key = `${it.category || ''}/${it.name}`;
        if (seen.has(key)) return;
        seen.add(key);
        addItem(gameId, zoneId, it.name, it.total || 1, { description: it.description || null });
      });
    }

    setOpen(false);
  };

  return (
    <>
      <div className="bg-emerald-500/10 border border-emerald-500/30 rounded-lg px-3 py-2 flex items-center gap-2 text-xs">
        <div className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse" />
        <span className="text-emerald-300 font-medium flex-1 truncate">
          {detectedGame.name} d&eacute;tect&eacute;
        </span>
        <button
          onClick={() => toggleAutoSync()}
          disabled={!matchedGameId || !detectedGame?.id}
          title={matchedGameId ? 'Synchronisation auto avec les fichiers de save' : 'Importe d\'abord la checklist'}
          className={`px-2 py-0.5 rounded disabled:opacity-30 ${
            autoSyncEnabled
              ? 'bg-emerald-500 text-black font-medium'
              : 'bg-emerald-500/20 hover:bg-emerald-500/30 text-emerald-200'
          }`}
        >
          {autoSyncEnabled ? 'Auto ON' : 'Auto'}
        </button>
        <button
          onClick={async () => {
            setSteamScanning(true);
            const r = await scanSteamNow();
            setSteamResult(r?.steam || null);
            setSteamScanning(false);
          }}
          disabled={steamScanning || !matchedGameId}
          title="Synchroniser avec tes achievements Steam"
          className="px-2 py-0.5 bg-blue-500/20 hover:bg-blue-500/30 text-blue-200 rounded disabled:opacity-30"
        >
          {steamScanning ? 'Steam...' : 'Steam'}
        </button>
        <button
          onClick={() => setSteamConfigOpen(true)}
          title="Configurer Steam (SteamID + cle API optionnelle)"
          className="px-1.5 py-0.5 bg-blue-500/10 hover:bg-blue-500/20 text-blue-200 rounded"
        >
          ⚙
        </button>
        <button
          onClick={() => setBrowserOpen(true)}
          title="Parcourir / cr\u00e9er des templates"
          className="px-2 py-0.5 bg-blue-500/10 hover:bg-blue-500/20 text-blue-200 rounded"
        >
          Templates
        </button>
        {detectedGame.autoGenerated ? (
          <button
            onClick={handleAutoGenerate}
            disabled={autoGenerating}
            title="Generer automatiquement une checklist depuis les achievements Steam"
            className="px-2 py-0.5 bg-amber-500/30 hover:bg-amber-500/40 text-amber-100 rounded disabled:opacity-50 font-medium"
          >
            {autoGenerating ? 'Generation...' : 'Generer auto'}
          </button>
        ) : (
          <button
            onClick={handleScan}
            disabled={scanning}
            className="px-2 py-0.5 bg-emerald-500/20 hover:bg-emerald-500/30 text-emerald-200 rounded disabled:opacity-50"
          >
            {scanning ? 'Scan...' : 'Importer'}
          </button>
        )}
      </div>

      {autoGenError && (
        <div className="mt-1 text-[11px] px-2 py-1 bg-red-500/10 border border-red-500/30 rounded text-red-300">
          {autoGenError}
        </div>
      )}

      <SteamConfigDialog open={steamConfigOpen} onClose={() => setSteamConfigOpen(false)} />
      <TemplateBrowser
        open={browserOpen}
        onClose={() => setBrowserOpen(false)}
        onImport={importRegistryGame}
      />

      {steamResult && (
        <div className="mt-1 text-[11px] px-2 bg-blue-500/5 border border-blue-500/20 rounded p-2">
          <div className="flex items-start gap-2">
            <div className="flex-1">
              {steamResult.error ? (
                <div className="text-red-400/80">{steamResult.error}</div>
              ) : (
                <div className="text-blue-300/90">
                  <span className="font-medium">
                    {steamResult.unlocked?.length || 0}
                  </span>
                  <span className="text-white/50">
                    {' '}/{' '}{steamResult.allAchievements?.length || 0}
                  </span>{' '}
                  succ&egrave;s d&eacute;bloqu&eacute;s
                </div>
              )}
              {steamResult.allAchievements?.length > 0 && (
                <details className="mt-1 text-white/60">
                  <summary className="cursor-pointer hover:text-white/80 text-[10px]">
                    Voir la liste
                  </summary>
                  <div className="mt-1 max-h-40 overflow-y-auto text-[10px]">
                    {steamResult.allAchievements.slice(0, 200).map((a, i) => (
                      <AchievementLine key={a.key || i} achievement={a} />
                    ))}
                  </div>
                </details>
              )}
            </div>
            <button
              onClick={() => setSteamResult(null)}
              className="text-white/40 hover:text-white"
              aria-label="Fermer"
            >
              &times;
            </button>
          </div>
        </div>
      )}

      {autoSyncEnabled && (
        <div className="mt-1 text-[10px] px-2 truncate">
          {savePulse && (
            <span className="text-yellow-400/80 mr-2">● Save modifi&eacute;</span>
          )}
          {autoChecked.length > 0 ? (
            <span className="text-emerald-400/80">
              ✓ {autoChecked[0].name} ({autoChecked[0].zone})
            </span>
          ) : lastEvent ? (
            <span className="text-white/40">
              Sauvegarde d&eacute;tect&eacute;e
            </span>
          ) : (
            <span className="text-white/30">En attente d'une sauvegarde...</span>
          )}
        </div>
      )}

      {open && scanResult && (
        <div className="fixed inset-0 z-50 bg-black/70 flex items-center justify-center p-4">
          <div className="bg-dark-900 border border-white/10 rounded-xl max-w-lg w-full max-h-[80vh] overflow-hidden flex flex-col">
            <div className="px-4 py-3 border-b border-white/10 flex items-center justify-between">
              <h3 className="text-white font-semibold">
                Donn&eacute;es d&eacute;tect&eacute;es - {scanResult.gameName}
              </h3>
              <button onClick={() => setOpen(false)} className="text-white/40 hover:text-white">
                &times;
              </button>
            </div>

            <div className="p-4 overflow-y-auto flex-1 space-y-3">
              {scanResult.files.length === 0 && (
                <p className="text-white/50 text-sm">
                  Aucun fichier de sauvegarde lisible trouv&eacute;. La checklist sera cr&eacute;&eacute;e
                  &agrave; partir du mod&egrave;le par d&eacute;faut.
                </p>
              )}

              {scanResult.aggregated.items.length > 0 ? (
                <div className="text-emerald-300 text-sm font-medium">
                  {scanResult.aggregated.items.length} item(s) pr&ecirc;ts &agrave; importer
                </div>
              ) : scanResult.files.length > 0 ? (
                <div className="text-white/50 text-sm">
                  Sauvegarde d&eacute;tect&eacute;e mais aucun item extractible.
                  Une checklist par d&eacute;faut sera cr&eacute;&eacute;e.
                </div>
              ) : null}
            </div>

            <div className="px-4 py-3 border-t border-white/10 flex justify-end gap-2">
              <button
                onClick={() => setOpen(false)}
                className="px-3 py-1.5 text-sm text-white/60 hover:text-white"
              >
                Annuler
              </button>
              <button
                onClick={handleImport}
                className="px-3 py-1.5 text-sm bg-emerald-500 hover:bg-emerald-400 text-black font-medium rounded"
              >
                Importer dans la checklist
              </button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
