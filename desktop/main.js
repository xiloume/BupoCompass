ipcMain.handle('steam:get-game-schema', async (_event, gameId) => {
  try {
    const reg = loadRegistry();
    const game = reg.games.find((g) => g.id === gameId);
    if (!game?.steamAppId) return { error: 'Pas de steamAppId' };
    const schema = await fetchGameSchema(game.steamAppId);
    return { schema, appId: game.steamAppId };
  } catch (e) {
    return { error: e.message };
  }
});

