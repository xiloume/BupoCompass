// Auto-size the window height (used by compact mode to fit items list).
ipcMain.on('resize-window', (_event, { width, height } = {}) => {
  try {
    const bounds = mainWindow.getBounds();
    const targetW = Math.max(200, Math.min(1200, Math.round(width || bounds.width)));
    const targetH = Math.max(80, Math.min(1200, Math.round(height || bounds.height)));
    mainWindow.setBounds({ x: bounds.x, y: bounds.y, width: targetW, height: targetH }, false);
  } catch {}
});
