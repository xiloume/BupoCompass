// --- Template generation handlers ---

ipcMain.handle('templates:search-steam', async (_event, query) => {
  try {
    if (!query || query.trim().length < 2) return { results: [] };
    const results = await searchSteamGames(query, 20);
    console.log(`[templates] Steam search "${query}" -> ${results.length} results`);
    return { results };
  } catch (e) {
    console.error('[templates] Steam search failed:', e);
    return { error: `Recherche Steam impossible: ${e.message}`, results: [] };
  }
});

ipcMain.handle('templates:generate', async (_event, appId, opts = {}) => {
  try {
    const entry = await generateTemplateForAppId(Number(appId), opts);
    return { ok: true, entry };
  } catch (e) {
    return { ok: false, error: e.message };
  }
});

ipcMain.handle('templates:save', async (_event, entry) => {
  try {
    if (!entry || !entry.id) {
      // Auto-generate id from name or appId
      const slug = String(entry.name || `game-${entry.steamAppId}`)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)/g, '');
      entry.id = slug;
    }
    if (!entry.processNames) entry.processNames = [];
    if (!entry.saveLocations) entry.saveLocations = [];
    if (!entry.scanTargets) entry.scanTargets = [];
    upsertGameInRegistry(entry);
    return { ok: true, id: entry.id };
  } catch (e) {
    return { ok: false, error: e.message };
  }
});

ipcMain.handle('templates:list-local', () => {
  try {
    const reg = loadRegistry(true);
    return { games: reg.games || [] };
  } catch (e) {
    return { error: e.message, games: [] };
  }
});

ipcMain.handle('templates:delete', (_event, id) => {
  try {
    const reg = loadRegistry(true);
    const before = reg.games.length;
    reg.games = reg.games.filter((g) => g.id !== id);
    require('./gameDetector').saveRegistry(reg);
    return { ok: true, removed: before - reg.games.length };
  } catch (e) {
    return { ok: false, error: e.message };
  }
});

