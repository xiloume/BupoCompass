// Resolve a gameId to a game object. Falls back to Steam library for
// auto-detected games whose template hasn't been generated/saved yet.
async function resolveGame(gameId) {
  const reg = loadRegistry();
  const found = reg.games.find((g) => g.id === gameId);
  if (found) return found;
  const m = String(gameId || '').match(/^steam-(\d+)$/);
  if (!m) return null;
  const appId = Number(m[1]);
  const installed = await listInstalledSteamGames();
  const g = installed.find((x) => x.appId === appId);
  if (!g) return null;
  return {
    id: gameId,
    name: g.name,
    steamAppId: appId,
    processNames: g.exes || [],
    saveLocations: [],
    scanTargets: [],
    autoGenerated: true,
  };
}

let mainWindow;
let isInteractive = true;
let lastDetectedGameId = null;
let detectionInterval = null;
const COMPACT_HEIGHT = 50;
const DEFAULT_HEIGHT = 600;

function createWindow() {
  const { width: screenWidth, height: screenHeight } = screen.getPrimaryDisplay().workAreaSize;

  mainWindow = new BrowserWindow({
    x: screenWidth - 380,
    y: Math.floor(screenHeight / 2) - 300,
    width: 340,
    height: 600,
    transparent: true,
    frame: false,
    alwaysOnTop: true,
    skipTaskbar: false,
    resizable: true,
    minimizable: true,
    hasShadow: false,
    fullscreenable: false,
    // Non-focusable: clicks still register on buttons but the window
    // never steals focus from the active game. Toggled to true when
    // text inputs need keyboard (settings/template dialogs).
    focusable: false,
    icon: path.join(__dirname, '..', 'web', 'public', 'Bupo_compass_icon.png'),
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
    },
  });

  // Critical for overlay mode: 'screen-saver' z-level appears ABOVE fullscreen apps/games
  // (works for borderless windowed and most fullscreen games; exclusive fullscreen on some
  //  GPUs may still hide it - in that case users should set the game to borderless)
  mainWindow.setAlwaysOnTop(true, 'screen-saver');
  mainWindow.setVisibleOnAllWorkspaces(true, { visibleOnFullScreen: true });
  // Re-assert on focus events (some games steal the z-order)
  mainWindow.on('blur', () => {
    try { mainWindow.setAlwaysOnTop(true, 'screen-saver'); } catch {}
  });

  if (!app.isPackaged) {
    mainWindow.loadURL('http://localhost:5173');
  } else {
    mainWindow.loadFile(path.join(__dirname, '..', 'dist', 'index.html'));
  }

  // Register global shortcuts
  globalShortcut.register('F9', () => {
    if (mainWindow.isVisible()) {
      mainWindow.hide();
    } else {
      mainWindow.show();
    }
  });

  globalShortcut.register('F10', () => {
    isInteractive = !isInteractive;
    mainWindow.setIgnoreMouseEvents(!isInteractive, { forward: true });
    mainWindow.webContents.send('interactive-changed', isInteractive);
  });
}

function startGameDetection() {
  // Poll every 8 seconds for a running known game
  const tick = async () => {
    try {
      const game = await detectRunningGame();
      const id = game?.id || null;
      if (id !== lastDetectedGameId) {
        lastDetectedGameId = id;
        if (mainWindow && !mainWindow.isDestroyed()) {
          mainWindow.webContents.send('game-detected', game);
        }
      }
    } catch (e) {
      // silent
    }
  };
  tick();
  detectionInterval = setInterval(tick, 8000);
}

app.whenReady().then(() => {
  createWindow();
  startGameDetection();
});

