ipcMain.handle('steam:scan-achievements', async (_event, gameId) => {
  try {
    const game = await resolveGame(gameId);
    if (!game) return { error: 'Jeu inconnu', unlocked: [] };
    if (!game.steamAppId) {
      return { error: 'Ce jeu ne supporte pas les achievements Steam', unlocked: [] };
    }

    const cfgStatus = getConfigStatus();
    const map = game.steamAchievementMap || {};
    const descMap = game.steamAchievementDescriptions || {};
    const errors = [];

    // Steam is queried with l=<lang>, so what the source returns is already
    // localized and must win. The registry template is only a fallback for
    // sources that carry no label at all (e.g. local file scan).
    const localize = (list) =>
      (list || []).map((a) => ({
        ...a,
        display: a.display || map[a.key] || a.key,
        description: a.description || descMap[a.key] || null,
      }));

    const respond = (r, source) => {
      const allAchievements = localize(r.allAchievements || r.achievements || []);

      // Persist the freshly localized labels so templates imported earlier
      // (possibly in English) converge to the configured language.
      if (allAchievements.length) {
        try {
          const nextMap = { ...map };
          const nextDesc = { ...descMap };
          let changed = false;
          for (const a of allAchievements) {
            if (!a.key) continue;
            if (a.display && nextMap[a.key] !== a.display) {
              nextMap[a.key] = a.display;
              changed = true;
            }
            if (a.description && nextDesc[a.key] !== a.description) {
              nextDesc[a.key] = a.description;
              changed = true;
            }
          }
          if (changed && game.id) {
            upsertGameInRegistry({
              id: game.id,
              name: game.name,
              steamAppId: game.steamAppId,
              processNames: game.processNames || [],
              steamAchievementMap: nextMap,
              steamAchievementDescriptions: nextDesc,
            });
          }
        } catch (e) {
          console.warn('[steam:scan] label refresh failed:', e.message);
        }
      }

      return {
        allAchievements,
        unlocked: allAchievements.filter((a) => a.unlocked),
        map,
        descMap,
        lang: cfgStatus.lang,
        appId: game.steamAppId,
        source,
      };
    };

    // 1. Try Steam Web API (most reliable, requires API key)
    if (cfgStatus.hasApiKey && cfgStatus.hasSteamId) {
      try {
        return respond(await fetchPlayerAchievements(game.steamAppId), 'web-api');
      } catch (e) {
        errors.push(`API: ${e.message}`);
      }
    }

    // 2. Try public profile XML (no API key required, just needs public profile + SteamID)
    if (cfgStatus.hasSteamId) {
      try {
        return respond(await fetchPublicAchievements(game.steamAppId), 'public-profile');
      } catch (e) {
        errors.push(`Public: ${e.message}`);
      }
    }

    // 3. Fallback: local file scan (best-effort). Steam's local cache is not
    //    localized either, so translate it like the public profile.
    try {
      const r = await getAchievementsForApp(game.steamAppId);
      if (r.unlocked?.length || r.allAchievements?.length) {
        const localized = await localizeAchievements(
          game.steamAppId,
          r.allAchievements || [],
          cfgStatus.lang,
          cfgStatus.steamId
        );
        return respond({ allAchievements: localized }, 'local');
      }
    } catch (e) {
      errors.push(`Local: ${e.message}`);
    }

    // Nothing worked - return user-friendly error
    let userError;
    if (!cfgStatus.hasSteamId) {
      userError = 'Configure ton SteamID dans les param\u00e8tres pour lire tes achievements';
    } else {
      userError = 'Achievements introuvables. V\u00e9rifie que ton profil Steam est public ou ajoute une cl\u00e9 API';
    }
    return { error: userError, unlocked: [], allAchievements: [] };
  } catch (e) {
    console.error('[steam:scan-achievements] failed:', e);
    return { error: 'Erreur lors du scan Steam', unlocked: [] };
  }
});

