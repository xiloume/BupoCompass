const { exec } = require('child_process');
const fs = require('fs');
const path = require('path');

let registry = null;
const BUNDLED_REGISTRY_PATH = path.join(__dirname, 'games', 'registry.json');
let cachedRegistryPath = null;

// In a packaged build the app lives inside app.asar which is READ-ONLY, so the
// registry must live in the user data folder. The bundled file is used as seed.
function getRegistryPath() {
  if (cachedRegistryPath) return cachedRegistryPath;
  let writablePath = BUNDLED_REGISTRY_PATH;
  try {
    const { app } = require('electron');
    if (app?.isPackaged) {
      const dir = path.join(app.getPath('userData'), 'games');
      fs.mkdirSync(dir, { recursive: true });
      writablePath = path.join(dir, 'registry.json');
      if (!fs.existsSync(writablePath)) {
        const seed = fs.existsSync(BUNDLED_REGISTRY_PATH)
          ? fs.readFileSync(BUNDLED_REGISTRY_PATH, 'utf8')
          : JSON.stringify({ games: [] }, null, 2);
        fs.writeFileSync(writablePath, seed, 'utf8');
      }
    }
  } catch (e) {
    console.warn('[GameDetector] registry path fallback:', e.message);
  }
  cachedRegistryPath = writablePath;
  return cachedRegistryPath;
}

function loadRegistry(forceReload = false) {
  if (registry && !forceReload) return registry;
  try {
    registry = JSON.parse(fs.readFileSync(getRegistryPath(), 'utf8'));
  } catch (e) {
    console.error('[GameDetector] registry unreadable:', e.message);
    registry = { games: [] };
  }
  if (!Array.isArray(registry.games)) registry.games = [];
  return registry;
}

function saveRegistry(reg) {
  fs.writeFileSync(getRegistryPath(), JSON.stringify(reg, null, 2), 'utf8');
  registry = reg;
  return reg;
}

function upsertGameInRegistry(gameEntry) {
  const reg = loadRegistry(true);
  if (!reg.games) reg.games = [];
  const idx = reg.games.findIndex(
    (g) => g.id === gameEntry.id || (gameEntry.steamAppId && g.steamAppId === gameEntry.steamAppId)
  );
  if (idx >= 0) {
    reg.games[idx] = { ...reg.games[idx], ...gameEntry };
  } else {
    reg.games.push(gameEntry);
  }
  saveRegistry(reg);
  return gameEntry;
}

// List running processes on Windows via tasklist
function listProcesses() {
  return new Promise((resolve, reject) => {
    if (process.platform !== 'win32') {
      // Fallback for Linux/Mac
      exec('ps -eo comm,args', (err, stdout) => {
        if (err) return resolve([]);
        const lines = stdout.split('\n').slice(1);
        resolve(
          lines
            .map((l) => l.trim())
            .filter(Boolean)
            .map((l) => {
              const [name, ...args] = l.split(/\s+/);
              return { name, args: args.join(' ') };
            })
        );
      });
      return;
    }

    exec('tasklist /FO CSV /NH', { maxBuffer: 1024 * 1024 * 5 }, (err, stdout) => {
      if (err) return reject(err);
      const procs = stdout
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean)
        .map((line) => {
          const cols = line.split('","').map((c) => c.replace(/^"|"$/g, ''));
          return { name: cols[0] || '', args: '' };
        });
      resolve(procs);
    });
  });
}

// Detect which known game (if any) is currently running.
// Order: (1) registry match  ->  (2) any installed Steam game by process name.
async function detectRunningGame() {
  const reg = loadRegistry();
  const procs = await listProcesses();
  const procNamesLower = procs.map((p) => p.name.toLowerCase());
  const procSet = new Set(procNamesLower);

  // (1) registry first
  for (const game of reg.games) {
    const matched = game.processNames.some((pn) => {
      const target = pn.toLowerCase();
      const targetNoExt = target.replace(/\.exe$/, '');
      return procNamesLower.some((n) => {
        const nNoExt = n.replace(/\.exe$/, '');
        return n === target || nNoExt === targetNoExt;
      });
    });
    if (matched) {
      console.log(`[GameDetector] Detected (registry): ${game.name}`);
      return game;
    }
  }

  // (2) fallback: any installed Steam game whose .exe is running
  try {
    const { listInstalledSteamGames } = require('./steamLibrary');
    const installed = await listInstalledSteamGames();
    for (const g of installed) {
      const hit = g.exes.find((exe) => procSet.has(exe.toLowerCase()));
      if (hit) {
        console.log(`[GameDetector] Detected (Steam lib): ${g.name} via ${hit}`);
        return {
          id: `steam-${g.appId}`,
          name: g.name,
          steamAppId: g.appId,
          processNames: [hit],
          autoGenerated: true,
          installRoot: g.installRoot,
        };
      }
    }
  } catch (e) {
    console.warn('[GameDetector] Steam library scan failed:', e.message);
  }

  return null;
}

// Debug: get all processes (used by UI for diagnostics)
async function getAllProcessNames() {
  const procs = await listProcesses();
  return [...new Set(procs.map((p) => p.name).filter(Boolean))].sort();
}

// Resolve env vars like %APPDATA%, %USERPROFILE% in a path
function resolveEnvPath(p) {
  return p.replace(/%([^%]+)%/g, (_, key) => process.env[key] || '');
}

module.exports = {
  loadRegistry,
  saveRegistry,
  upsertGameInRegistry,
  listProcesses,
  detectRunningGame,
  getAllProcessNames,
  resolveEnvPath,
};
